def grocery_category_for(name: str) -> str:
    text = (name or "").lower()
    for cat, keys in GROCERY_KEYWORDS.items():
        if any(k in text for k in keys):
            return cat
    return "other"


def estimate_item_cost(name: str, amount: float | None, unit: str | None) -> float:
    text = (name or "").lower()
    price = 15.0
    for key, val in PRICE_PER_UNIT.items():
        if key in text:
            price = val
            break
    qty = amount or 1
    u = (unit or "").lower()
    if u in ("г", "гр", "g"):
        return round(price * (qty / 100.0), 1)
    if u in ("кг", "kg"):
        return round(price * qty * 10, 1)
    if u in ("мл", "ml"):
        return round(price * (qty / 200.0), 1)
    if u in ("л", "l"):
        return round(price * qty * 4, 1)
    return round(price * max(qty, 1) * 0.4, 1)


def current_season_products(month: int | None = None) -> list[str]:
    month = month or datetime.now().month
    return SEASONAL.get(month, [])


def cheaper_swap_for(name: str) -> dict | None:
    text = (name or "").lower()
    for row in CHEAPER_SWAPS:
        if row["from"] in text:
            return row
    return None
